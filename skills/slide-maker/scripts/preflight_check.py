# ── Three shipped-text defects that are decidable from the built file, and each of which cost
#    a full render→critic round before this existed. They are grouped apart from the twelve
#    because they are not PRE-FLIGHT items; they are the mechanical residue the render loop was
#    being used to discover instead of confirm.

MONO_FACES = ("menlo", "consolas", "courier", "monaco", "sf mono", "dejavu sans mono")
FULLWIDTH_CLOSERS = "。，、；：！？）》」』】"
# a HALF-WIDTH Latin/digit glyph immediately followed by a full-width mark: PowerPoint's and
# LibreOffice's CJK/Latin auto-spacing then opens a gap BEFORE the punctuation, which
# python-pptx cannot switch off. The only fix is to not write the adjacency.
# The left class is deliberately ASCII-only — a full-width `）` before `：` is ordinary Chinese
# punctuation with no script boundary, so including it produced false positives.
LATIN_THEN_FW = re.compile(rf"([A-Za-z0-9%+\)\]])([{FULLWIDTH_CLOSERS}])")


def _paras(slide):
    """(shape, paragraph_text, max_pt, {font names}, sy) for every non-empty text paragraph."""
    for sh, _sx, sy in _leaves(slide.shapes):
        if not sh.has_text_frame:
            continue
        for p in sh.text_frame.paragraphs:
            txt = "".join(r.text for r in p.runs)
            if not txt.strip():
                continue
            sizes = [r.font.size.pt for r in p.runs if r.font.size is not None]
            fonts = {(r.font.name or "").lower() for r in p.runs if r.font.name}
            yield sh, txt, (max(sizes) if sizes else None), fonts, sy


def _inner_width_in(sh) -> float:
    tf = sh.text_frame
    ml = (tf.margin_left or 0) / 914400
    mr = (tf.margin_right or 0) / 914400
    return sh.width / 914400 - ml - mr


def _face_installed(name: str) -> bool:
    """Is this font actually on this machine? Cheap, no matplotlib import."""
    import glob
    import os
    stem = re.sub(r"[^a-z0-9]", "", name.lower())
    if not stem:
        return False
    for d in ("/System/Library/Fonts", "/System/Library/Fonts/Supplemental", "/Library/Fonts",
              os.path.expanduser("~/Library/Fonts"), "/usr/share/fonts", "/usr/local/share/fonts"):
        for p in glob.glob(os.path.join(d, "**", "*"), recursive=True):
            if stem in re.sub(r"[^a-z0-9]", "", os.path.basename(p).lower()):
                return True
    return False


def check_mono_wrap(prs):
    """A broken command line is not a cosmetic defect — it is a WRONG command.

    Measured: a deck shipped `npx skills add addsumtech/slides_maker` in a code panel. In the
    render it came out as three lines, and the visible text copied as
    `…/slides_maker/slide-maker` — a repo path that 404s. The one line a persuaded reader must
    transcribe correctly was the broken one, and nothing flagged it: `code_block` sets
    word_wrap=False, so a too-long line OVERFLOWS its panel instead of wrapping, and an
    overflow inside a panel is invisible to every geometry check.

    Two things make this checkable, and the second is the one that actually bit:
      1. width — monospace is fixed-advance, so `chars x advance x pt` against the box's own
         inner width is exact. 0.62em is used deliberately: at or above every common mono face,
         so the check errs toward warning early.
      2. SUBSTITUTION — deckkit's default MONO is 'Consolas', a Windows face absent from macOS
         and most Linux boxes. When it is missing the renderer picks something wider, so a line
         that fits nominally still breaks. The historical failure fit with ~10% margin and
         broke anyway. A line inside 15% of its box is therefore reported as tight, and a
         missing mono face is reported outright.
    """
    over, tight, missing = [], [], set()
    for i, s in enumerate(prs.slides, 1):
        for sh, txt, pt, fonts, _sy in _paras(s):
            mono = [f for f in fonts if any(m in f for m in MONO_FACES)]
            if not pt or not mono:
                continue
            for f in mono:
                if not _face_installed(f):
                    missing.add(f)
            avail = _inner_width_in(sh)
            need = len(txt) * 0.62 * pt / 72.0
            if need > avail:
                over.append(f"s{i} needs {need:.2f}in in {avail:.2f}in: {txt[:40]!r}")
            elif need > 0.85 * avail:
                tight.append(f"s{i} {need:.2f}/{avail:.2f}in ({need/avail:.0%}): {txt[:40]!r}")
    if over:
        return "FAIL", (f"{len(over)} mono line(s) overflow their panel (word_wrap is off, so "
                        f"they run off it silently) — " + " · ".join(over[:3]))
    if missing:
        return "FAIL", (f"mono face not installed: {', '.join(sorted(missing))} — the renderer "
                        f"substitutes a different width, so the panel you checked is not the "
                        f"panel a reader sees. Set deckkit.MONO to an installed face.")
    if tight:
        return "ADVISORY", (f"{len(tight)} mono line(s) fill >85% of the panel — a substituted "
                            f"face will break them; drop a point or widen — " + " · ".join(tight[:2]))
    return "PASS", "every monospace line fits its panel with margin, in an installed face"


def check_latin_fullwidth(prs):
    """A space appears BEFORE full-width punctuation that follows a Latin run.

    Shipped on 5 of 12 slides in a real deck and found only by a human at 5x zoom: `原生 PPTX 。`,
    `既搭 deck 、又给它打分`, `（第 3 、 5 步）`. The renderer's CJK/Latin auto-spacer inserts the gap
    and python-pptx has no switch for it, so the adjacency itself is the defect — reword so a
    CJK glyph precedes the mark, or drop the mark.
    """
    bad = []
    for i, s in enumerate(prs.slides, 1):
        for _sh, txt, _pt, _f, _sy in _paras(s):
            for m in LATIN_THEN_FW.finditer(txt):
                bad.append(f"s{i} '…{m.group(1)}{m.group(2)}…' in {txt[:30]!r}")
    if bad:
        return "FAIL", f"{len(bad)} Latin→full-width adjacency — " + " · ".join(bad[:3])
    return "PASS", "no Latin glyph sits immediately before full-width punctuation"


def check_box_geometry(prs):
    """A text box with no usable interior — the silent class.

    `h = card_h - 1.42` with card_h = 1.30 yields -0.12; python-pptx stores it, the run
    overflows a box that has no inside, and every geometry check stays green because there is
    nothing to overlap. deckkit.text() now raises on this at the call site; this catches decks
    built by other means, and boxes too short to hold one line of their own type.
    """
    hard, soft = [], []
    for i, s in enumerate(prs.slides, 1):
        for sh, txt, pt, _f, sy in _paras(s):
            # rendered height, not stored height: a group rescales its children
            h = sh.height * sy / 914400
            if h <= 0 or sh.width / 914400 <= 0:
                hard.append(f"s{i} {sh.width/914400:.2f}x{h:.2f}in {txt[:24]!r}")
            elif pt and h < 0.60 * pt / 72.0:
                soft.append(f"s{i} {h:.2f}in box for {pt:g}pt {txt[:24]!r}")
    if hard:
        return "FAIL", f"{len(hard)} non-positive text box(es) — " + " · ".join(hard[:3])
    if soft:
        return "ADVISORY", f"{len(soft)} box under half a line tall — " + " · ".join(soft[:2])
    return "PASS", "every text box has a usable interior"


# Primitives that DERIVE a stack's geometry from the space available, so gaps and pitch come out
# right by construction. SKILL.md's rule is "derive the stack pitch from the region — never
# `block_h + 0.02`"; these are what "derive" means in code.
_MEAN_FNS = {"mean", "average", "avg", "nanmean", "median", "nanmedian"}


def check_bar_of_means(build_path):
    """A BAR of sample means — the one chart choice the literature calls a defect, not a taste.

    A bar's length encodes a value filling the range from zero, which is a claim about a COUNT. When
    the value is instead the mean of measurements, the bar hides n, the shape of the spread and any
    outlier, and invites reading two bar heights as if the underlying samples did not overlap
    (Nature Methods, *Kick the bar chart habit*; PLOS Biology, *Beyond Bar and Line Graphs*).
    `designed_charts.distribution` is the replacement, and it picks box vs mean±error by n itself.

    Detected structurally, not by naming convention: the script computes a mean/median AND feeds that
    same variable to a column/bar `native_chart`. Deliberately narrow — a bar of COUNTS never trips
    it, and a LINE of means (a trend of averages, entirely legitimate) never trips it either.

    ADVISORY, not FAIL: a mean over a full POPULATION rather than a sample is a fair bar, and nothing
    in the file distinguishes the two. Failing on that would train people to ignore the tool.
    """
    if not build_path:
        return "NOT CHECKABLE", "no --build script given"
    try:
        src = Path(build_path).read_text()
        tree = ast.parse(src)
    except (OSError, SyntaxError) as e:
        return "NOT CHECKABLE", f"build script unreadable ({type(e).__name__})"

    mean_vars = set()
    for node in ast.walk(tree):
        if not isinstance(node, ast.Assign):
            continue
        calls = [c for c in ast.walk(node.value) if isinstance(c, ast.Call)]
        names = {(c.func.attr if isinstance(c.func, ast.Attribute)
                  else c.func.id if isinstance(c.func, ast.Name) else "") for c in calls}
        if names & _MEAN_FNS:
            for tgt in node.targets:
                mean_vars |= {s.id for s in ast.walk(tgt) if isinstance(s, ast.Name)}

    hits = []
    for node in ast.walk(tree):
        if not (isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute)
                and node.func.attr == "native_chart"):
            continue
        kind = next((k.value.value for k in node.keywords
                     if k.arg == "kind" and isinstance(k.value, ast.Constant)), "line_markers")
        if not str(kind).startswith(("column", "bar")):
            continue
        used = {s.id for a in node.args for s in ast.walk(a) if isinstance(s, ast.Name)}
        used |= {s.id for k in node.keywords for s in ast.walk(k.value) if isinstance(s, ast.Name)}
        shared = sorted(used & mean_vars)
        if shared:
            hits.append((node.lineno, kind, shared))
    if not hits:
        return "PASS", ("no bar/column chart is fed a computed mean"
                        if mean_vars else "no means computed in the build")
    ln, kind, shared = hits[0]
    return "ADVISORY", (f"line {ln}: native_chart(kind={kind!r}) is fed {', '.join(shared)}, which "
                        f"holds a computed mean/median — a bar of SAMPLE means hides n, the spread "
                        f"and outliers. Use designed_charts.distribution (box at n>=5, mean+/-error "
                        f"at n=3-4). Ignore only if these are POPULATION means, not a sample"
                        + (f"; {len(hits)-1} more" if len(hits) > 1 else ""))


DERIVERS = ("vstack", "rows", "columns", "content_band", "spaced_centers", "bottom_callout",
            "measure_text", "measure_bullets", "measure_callout", "fit_text_size")
_COORD = re.compile(r"^(x{1,2}|y{1,2}|c[xy]|[tblr]y|[tblr]x)$|_[xy]$")


def check_handrolled_pitch(build_path):
    """A LITERAL stride constant inside a placement loop — the documented #1 geometry defect.

    SKILL.md warns about this at length and the warning is prose, so it gets read and then not
    done. Measured on one deck: the author called ZERO of `vstack` / `rows` / `columns` /
    `content_band` / `bottom_callout`, hand-rolled every stack as `y += 0.72` / `yy += 0.62`, and
    shipped roughly fifteen geometry defects from that arithmetic — a negative-height text box, a
    pitch that overran its panel, text past a card bottom, two footer intrusions. The two pages
    built from a real component (`table`, `timeline`) had almost none. So the gap was never tool
    availability; it was that nothing noticed the tool going unused.

    The rule is deliberately narrow, and the narrowness is what makes it trustworthy: only a
    LITERAL constant is a finding. A stride computed from the region —
    `bh = ((bottom - top) - gap * (n - 1)) / n` then `y = top + i * (bh + gap)` — is exactly the
    correct pattern and must never be flagged. That distinction is the same one SKILL.md draws.
    """
    if not build_path:
        return "NOT CHECKABLE", "pass --build <build_x.py> to check the build script"
    p = Path(build_path)
    if not p.is_file():
        return "NOT CHECKABLE", f"no such build script: {p}"
    try:
        tree = ast.parse(p.read_text(encoding="utf-8", errors="replace"))
    except SyntaxError as e:
        return "NOT CHECKABLE", f"could not parse {p.name}: {e}"

    hits, used = [], set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute):
            if node.func.attr in DERIVERS:
                used.add(node.func.attr)
        elif isinstance(node, ast.Call) and isinstance(node.func, ast.Name):
            if node.func.id in DERIVERS:
                used.add(node.func.id)

    for fn in [n for n in ast.walk(tree) if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))]:
        # a function that already derives its geometry is not the target
        derives_here = any(
            (isinstance(c, ast.Call) and
             ((isinstance(c.func, ast.Attribute) and c.func.attr in DERIVERS) or
              (isinstance(c.func, ast.Name) and c.func.id in DERIVERS)))
            for c in ast.walk(fn))
        if derives_here:
            continue
        for loop in [n for n in ast.walk(fn) if isinstance(n, (ast.For, ast.While))]:
            # `for i, (a, b) in enumerate(...)` binds a TUPLE, and that is the commonest form —
            # reading only ast.Name here silently missed every `y = base + i * 0.5` in it.
            tgts = {n.id for n in ast.walk(loop.target) if isinstance(n, ast.Name)} \
                if getattr(loop, "target", None) is not None else set()
            for n in ast.walk(loop):
                # y += 0.62   (accumulate with a literal)
                if (isinstance(n, ast.AugAssign) and isinstance(n.op, ast.Add)
                        and isinstance(n.target, ast.Name) and _COORD.search(n.target.id)
                        and isinstance(n.value, ast.Constant)
                        and isinstance(n.value.value, (int, float))):
                    hits.append((fn.name, n.lineno, f"{n.target.id} += {n.value.value}"))
                # y = base + i * 0.50   (index stride with a literal)
                if isinstance(n, ast.Assign) and isinstance(n.value, ast.BinOp):
                    for b in ast.walk(n.value):
                        if (isinstance(b, ast.BinOp) and isinstance(b.op, ast.Mult)
                                and isinstance(b.right, ast.Constant)
                                and isinstance(b.right.value, (int, float))
                                and isinstance(b.left, ast.Name) and b.left.id in tgts):
                            t0 = n.targets[0]
                            if isinstance(t0, ast.Name) and _COORD.search(t0.id):
                                hits.append((fn.name, n.lineno,
                                             f"{t0.id} = … + {b.left.id} * {b.right.value}"))
    if hits:
        seen, uniq = set(), []
        for h in hits:
            if h[:1] + h[2:] not in seen:
                seen.add(h[:1] + h[2:])
                uniq.append(h)
        detail = " · ".join(f"{f}():{ln} `{expr}`" for f, ln, expr in uniq[:4])
        return "FAIL", (f"{len(uniq)} hand-picked stride constant(s) in placement loops — derive the "
                        f"pitch from the region instead ({', '.join(DERIVERS[:4])}…); "
                        f"used here: {sorted(used) or 'NONE of them'} — " + detail)
    return "PASS", (f"no literal stride constants in placement loops"
                    + (f" · derives via {sorted(used)}" if used else ""))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("deck")
    ap.add_argument("--build", help="the deck's build_<name>.py, for plan<->code checks")
    ap.add_argument("--selfread", action="store_true")
    ap.add_argument("--static", action="store_true")
    a = ap.parse_args()

    deck = Path(a.deck)
    if not deck.is_file():
        print(f"NOT CHECKED - no such deck: {deck}", file=sys.stderr)
        return 2
    try:
        prs = load_deck(deck)
    except Exception as e:
        print(f"NOT CHECKED - could not open {deck}: {e}", file=sys.stderr)
        return 2

    checks = [
        (1,  "Speaker notes",          item1_notes(prs, a.selfread)),
        (2,  "Builds staged",          item2_builds(prs, a.static)),
        (3,  "Plan<->code (build:)",   item3b_build_docstrings(a.build)),
        (4,  "Charts / math native",   item4_charts_equations(prs, a.build)),
        (7,  "Claims dated",           item7_as_of(prs)),
        (8,  "Language & hygiene",     item8_hygiene(prs)),
        (10, "Hand-off: fonts",        item10_fonts(prs)),
    ]

    residue = [
        ("mono wrap",        check_mono_wrap(prs)),
        ("Latin→full-width", check_latin_fullwidth(prs)),
        ("box geometry",     check_box_geometry(prs)),
        ("derived pitch",    check_handrolled_pitch(a.build)),
        ("bar of means",     check_bar_of_means(a.build)),
    ]

    print(f"PRE-FLIGHT (mechanical subset) — {deck.name}")
    fails = 0
    for n, name, (status, detail) in checks:
        mark = {"PASS": "✓", "FAIL": "✗", "ADVISORY": "!", "NOT CHECKABLE": "—"}[status]
        if status == "FAIL":
            fails += 1
        print(f"  {mark} {n:>2}. {name:<22} {detail}")

    print("\n  shipped-text residue (decidable here; each of these used to cost a render round):")
    for name, (status, detail) in residue:
        mark = {"PASS": "✓", "FAIL": "✗", "ADVISORY": "!", "NOT CHECKABLE": "—"}[status]
        if status == "FAIL":
            fails += 1
        print(f"  {mark}  ·  {name:<22} {detail}")

    print("\n  ( ! = advisory: real but undecidable from the file alone — read it, do not ignore it )")
    print("\n  NOT CHECKABLE BY ANY PROGRAM — these stay YOUR ticks, and this tool")
    print("  deliberately does not imply it covered them:")
    for k, (name, what) in JUDGMENT.items():
        print(f"    ? {str(k):>2}. {name:<26} {what}")
    print("\n    12. Form diversity            -> run scripts/component_audit.py (its own gate)")
    print("     3. Plan<->code (a)(c)        -> diff the design-plan rows + cover promises by hand")

    if fails:
        print(f"\n{fails} mechanical finding(s) — not ready to render.")
        return 1
    print("\nmechanical subset clean. The five judgment items above are still unticked.")
    return 0


