#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Which deck this IS was a fact only the operator's memory carried.

`render_deck.py --gate-check` has always read a `delivery` key out of `.deck-gates.json`.
`lint_deck.py` never did — it took the mode from CLI flags alone, and defaulted to `presented`.
So the same deck was one kind of artifact at hand-off and a different kind under the lint, and
staying consistent between them was an act of memory repeated on every run.

Measured on a delivered 14-page CJK self-read deck: **20 `[stats]` lines with no flags, 10 with
`--selfread`.** The ten were not weak signals to be argued with — they were the wrong budget on
the wrong deck: seven TEXT WALLs scored against the ~40-word *presented* budget instead of ~90,
a SMALL TYPE against the read-from-the-back floor, NO BUILDS, and "14 of 14 slides have empty
speaker notes" on a deck nobody speaks. Half the advisory output was noise the tool generated by
not knowing what it was looking at, and noise is what teaches people to skim gates.

Three pieces, all asserted here:
  · `deckkit.declare_delivery()` — the WRITE side, one line in the build script, merging into
    whatever `validate_review.py --record` already wrote;
  · `lint_deck._recorded_delivery()` + its CLI wiring — the READ side, with render_deck.py's
    precedence copied verbatim (recorded beats flag) so the two tools cannot disagree;
  · the contextual hint — printed only when a run was actually held to the default while emitting
    mode-sensitive warnings, because a deck that already answered the question must not be nagged.

`briefing` gets its own case: it is a real lint mode and NOT a recordable one, since render_deck
has no briefing floor and a recorded `briefing` would produce a deck that lints clean and cannot
be handed off. The refusal has to name that, not just reject the string.

Run:  python3 tests/test_delivery_record.py
"""
import json
import pathlib
import shutil
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
SCRIPTS = HERE.parent / "scripts"
sys.path.insert(0, str(SCRIPTS))

import deckkit as dk                                                  # noqa: E402
import lint_deck as ld                                                # noqa: E402

PASS, FAIL = [], []


def check(name, cond, detail=""):
    (PASS if cond else FAIL).append(name)
    print(("  ok   " if cond else "  FAIL ") + name
          + (("  — " + str(detail)) if detail and not cond else ""))


def build_deck(d, *, wordy=True):
    """A deck whose advisory lines are mode-sensitive: long bodies, no notes, no builds."""
    prs = dk.blank_deck()
    body = ("This paragraph exists to carry a reading load well past the presented budget of "
            "about forty words, while staying inside the self-read budget of about ninety, so "
            "that the very same file is a TEXT WALL under one delivery and clean under the "
            "other. " * (2 if wordy else 1))
    for i in range(3):
        s = dk.add_slide(prs)
        dk.title_bar(s, "A page with a real reading load", kicker="section")
        dk.footer(s, "test", page=i + 1)
        band = dk.content_band(s)
        dk.text(s, band[0], band[1], band[2], 2.4,
                [[(body, 12, dk.DEEP, False, False, dk.FONT)]])
    p = d / "deck.pptx"
    prs.save(str(p))
    return p


def run_lint(deck, *flags):
    r = subprocess.run([sys.executable, str(SCRIPTS / "lint_deck.py"), str(deck), *flags],
                       capture_output=True, text=True)
    return (r.stdout or "") + (r.stderr or "")


def stats_lines(out):
    return [l for l in out.splitlines() if "[stats]" in l]


def main():
    print("delivery record")
    tmp = pathlib.Path(tempfile.mkdtemp(prefix="deliv_"))
    try:
        deck = build_deck(tmp)
        gates = tmp / ".deck-gates.json"

        # ---- WRITE side ---------------------------------------------------------------
        gates.write_text(json.dumps({"critic": {"verdict": "consent", "reviews_seen": 2}}),
                         encoding="utf-8")
        p = dk.declare_delivery(str(deck), "selfread")           # given the .pptx path
        blob = json.loads(pathlib.Path(p).read_text(encoding="utf-8"))
        check("declare_delivery writes the key beside the deck", blob.get("delivery") == "selfread")
        check("...and MERGES, keeping what validate_review.py recorded", "critic" in blob)
        check("...and a directory works as well as a file path",
              json.loads(pathlib.Path(dk.declare_delivery(str(tmp), "presented"))
                         .read_text(encoding="utf-8"))["delivery"] == "presented")
        for bad in ("briefing", "Presented", "", None, "spoken"):
            try:
                dk.declare_delivery(str(tmp), bad)
                check("declare_delivery refuses %r" % (bad,), False)
            except ValueError:
                check("declare_delivery refuses %r" % (bad,), True)
        dk.declare_delivery(str(tmp), "presented")               # leave it in a known state

        # ---- READ side: the measured 20 -> 10 shape ------------------------------------
        gates.unlink()
        default = stats_lines(run_lint(deck))
        with_flag = stats_lines(run_lint(deck, "--selfread"))
        check("the default (presented) run reports MORE than the self-read run",
              len(default) > len(with_flag), (len(default), len(with_flag)))
        dk.declare_delivery(str(tmp), "selfread")
        recorded = stats_lines(run_lint(deck))
        check("recording the delivery reproduces the flag's result with NO flag",
              len(recorded) == len(with_flag), (len(recorded), len(with_flag)))
        check("...and the false positives that vanish are the mode-sensitive ones",
              not [l for l in recorded if "NO NOTES" in l]
              and bool([l for l in default if "NO NOTES" in l]))

        # ---- precedence: copied from render_deck.py, not re-decided ---------------------
        out = run_lint(deck, "--textheavy")
        check("a RECORDED value beats a conflicting flag", "using the RECORDED value" in out)
        check("...and says so loudly enough to fix whichever is wrong",
              "must not disagree" in out)
        check("a recorded value with no flag announces itself",
              "read from" in run_lint(deck))

        # ---- the refusals ---------------------------------------------------------------
        gates.write_text(json.dumps({"delivery": "briefing"}), encoding="utf-8")
        out = run_lint(deck)
        check("a recorded `briefing` is refused", "not a delivery mode" in out)
        check("...and the refusal explains WHY it is not recordable",
              "render_deck.py has no briefing floor" in out, out[-200:])
        r = subprocess.run([sys.executable, str(SCRIPTS / "lint_deck.py"), str(deck)],
                           capture_output=True, text=True)
        check("...and exits non-zero rather than linting at the wrong floor", r.returncode != 0,
              r.returncode)

        gates.write_text(json.dumps({"delivery": "wat"}), encoding="utf-8")
        check("an unrecognised value dies instead of falling back to presented",
              "not a delivery mode" in run_lint(deck))

        gates.write_text("{ this is not json", encoding="utf-8")
        check("an unreadable gates file does not break the lint",
              "[stats]" in run_lint(deck) or "layout finding" in run_lint(deck))
        gates.unlink(missing_ok=True)

        # ---- the hint fires exactly when it is useful ------------------------------------
        HINT = "assume a PRESENTED deck"
        check("with no record and no flag, the hint appears next to the lines it explains",
              HINT in run_lint(deck))
        check("...with a flag given, the question is answered — no nag",
              HINT not in run_lint(deck, "--selfread"))
        dk.declare_delivery(str(tmp), "presented")
        check("...with `presented` RECORDED, it is a decision, not a default — no nag",
              HINT not in run_lint(deck))

        # a deck with no mode-sensitive warnings at all must never see the hint
        dk.declare_delivery(str(tmp), "presented")
        (tmp / ".deck-gates.json").unlink()
        quiet = pathlib.Path(tempfile.mkdtemp(prefix="deliv_q_"))
        try:
            prs = dk.blank_deck()
            s = dk.add_slide(prs)
            dk.title_bar(s, "Short", kicker="x")
            dk.footer(s, "t", page=1)
            dk.text(s, 0.6, 2.0, 6.0, 0.6, [[("Six words on one page here", 20, dk.DEEP,
                                              False, False, dk.FONT)]])
            s.notes_slide.notes_text_frame.text = "spoken thread"
            qd = quiet / "q.pptx"
            prs.save(str(qd))
            out = run_lint(qd)
            check("a deck with no mode-sensitive warning never sees the hint",
                  HINT not in out, [l for l in stats_lines(out)][:3])
        finally:
            shutil.rmtree(quiet, ignore_errors=True)

        # ---- the enum is ONE enum -------------------------------------------------------
        check("lint and deckkit agree on the recordable modes",
              tuple(ld._KNOWN_DELIVERY) == tuple(dk.DELIVERY_MODES),
              (ld._KNOWN_DELIVERY, dk.DELIVERY_MODES))
        rd = (SCRIPTS / "render_deck.py").read_text(encoding="utf-8")
        check("...and so does render_deck.py, whose precedence rule this copies",
              '_KNOWN_DELIVERY = ("presented", "textheavy", "selfread", "surface")' in rd)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    print("\n{} passed, {} failed".format(len(PASS), len(FAIL)))
    return 1 if FAIL else 0


if __name__ == "__main__":
    sys.exit(main())
